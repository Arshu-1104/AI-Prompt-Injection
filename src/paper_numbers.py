"""Write paper/numbers.tex: every numeric value of the result artifacts as a LaTeX key.

The paper never contains a typed number. Each number in the text or a table is
\\pgr{digits}{key} (rounded), \\pgp{digits}{key} (as a percentage) or \\pgnum{key}
(as written), and each key is the artifact's short name plus the JSON path of the
value, so every \\pgdef line below also says where its number came from:

    \\pgdef{pr.models.classical.bootstrap.binary.accuracy.point}{0.958598726}
        % artifacts/paper_results.json

Lists of objects that carry a "name" are keyed by that name, other lists by index;
characters LaTeX cannot take in a control-sequence name are replaced by "_".
A key the paper uses but this file lacks prints as a bold ?? and a LaTeX warning.

    python -m src.paper_numbers
"""
from __future__ import annotations

import json
import math
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "paper" / "numbers.tex"
SOURCES = {  # short name -> file written by the code, relative to the repository root
    "pr": "artifacts/paper_results.json",
    "ext": "artifacts/external_eval.json",
    "cur": "artifacts/curves.json",
    "pipe": "artifacts/pipeline_eval.json",
    "docs": "artifacts/pasted_docs.json",
    "rob": "artifacts/robustness_v2.json",
    "diag": "artifacts/diagnosis.json",
    "e2e": "artifacts/e2e_latency.json",
    "xdiag": "artifacts/external_diagnostics.json",
    "meta": "data/dataset_meta.json",  # written by src.load_data: split sizes, derivation counts, build fractions
    "trn": "artifacts/metrics.json",  # src.train_classical: validation score of every classical candidate
    "bert42": "artifacts/paper_runs/bert/seed_42/metrics.json",  # training hyperparameters (reference seed)
    "guard42": "artifacts/paper_runs/guard/seed_42/metrics.json",
}
SKIP_KEYS = {"samples", "sample_texts", "imperative_verbs", "question_words", "points"}


def sanitize(part: str) -> str:
    return re.sub(r"[^A-Za-z0-9.\-_/+]", "_", str(part)).strip("_") or "_"


def flatten(value, prefix: str, out: dict[str, float]) -> None:
    if isinstance(value, bool):
        out[prefix] = int(value)
    elif isinstance(value, (int, float)):
        if not (isinstance(value, float) and (math.isnan(value) or math.isinf(value))):
            out[prefix] = value
    elif isinstance(value, dict):
        out[f"{prefix}.n_keys"] = len(value)  # e.g. how many candidates or models an object lists
        for key, item in value.items():
            if key not in SKIP_KEYS:
                flatten(item, f"{prefix}.{sanitize(key)}", out)
    elif isinstance(value, list):
        named = all(isinstance(item, dict) and "name" in item for item in value) and value
        for i, item in enumerate(value):
            flatten(item, f"{prefix}.{sanitize(item['name']) if named else i}", out)


def fmt(value) -> str:
    return str(value) if isinstance(value, int) else f"{value:.10g}"


def collect() -> tuple[dict[str, tuple[float, str]], list[str]]:
    numbers: dict[str, tuple[float, str]] = {}
    missing = []
    for short, relative in SOURCES.items():
        path = ROOT / relative
        if not path.exists():
            missing.append(relative)
            continue
        flat: dict[str, float] = {}
        flatten(json.loads(path.read_text(encoding="utf-8")), short, flat)
        for key, value in flat.items():
            numbers[key] = (value, relative)
    return numbers, missing


def main() -> Path:
    numbers, missing = collect()
    lines = [
        "% Generated by `python -m src.paper_numbers` - do not edit by hand.",
        "% Every value is copied from the artifact named in its comment; keys are short name + JSON path.",
        f"% Artifacts not found when generated: {', '.join(missing) or 'none'}",
    ]
    for key in sorted(numbers):
        value, source = numbers[key]
        lines.append(f"\\pgdef{{{key}}}{{{fmt(value)}}}% {source}")
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {len(numbers)} numbers to {OUTPUT.relative_to(ROOT)}; missing artifacts: {missing or 'none'}")
    return OUTPUT


if __name__ == "__main__":
    main()
